#!/bin/zsh
# Build a Developer ID–signed Flipgrade.app + zip for sharing.
# Notarization is optional (needs notarytool credentials); without it Gatekeeper
# still allows right-click → Open on the recipient Mac.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

IDENTITY="Developer ID Application: Mark Ryan Sallee (F296W5W82Q)"
VERSION="0.3.5"
BUILD="7"
DIST_DIR="${HOME}/Desktop/Flipgrade-Distribute"
APP="$DIST_DIR/Flipgrade.app"
ZIP="$DIST_DIR/Flipgrade-${VERSION}.zip"
ENTITLEMENTS="$DIST_DIR/Flipgrade.entitlements"

# Generated absolute paths (same as run.sh).
GENERATED="$ROOT/Sources/Flipgrade/Generated"
mkdir -p "$GENERATED"
# Public builds: no baked-in developer folder path.
cat > "$GENERATED/RepoPaths.swift" <<EOF
/// Auto-generated by Scripts/distribute.sh — do not edit by hand.
enum RepoPaths {
    static let defaultFolderPath: String? = nil
    static let repoRootPath: String? = nil
}
EOF

echo "Building Flipgrade (release)…"
swift build -c release

BIN="$ROOT/.build/release/Flipgrade"
rm -rf "$DIST_DIR"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key>
  <string>Flipgrade</string>
  <key>CFBundleIdentifier</key>
  <string>com.flipgrade.app</string>
  <key>CFBundleName</key>
  <string>Flipgrade</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>${VERSION}</string>
  <key>CFBundleVersion</key>
  <string>${BUILD}</string>
  <key>LSMinimumSystemVersion</key>
  <string>14.0</string>
  <key>NSHighResolutionCapable</key>
  <true/>
  <key>NSPrincipalClass</key>
  <string>NSApplication</string>
  <key>ATSApplicationFontsPath</key>
  <string>Fonts</string>
</dict>
</plist>
EOF

# Hardened-runtime entitlements (non-sandboxed Developer ID).
cat > "$ENTITLEMENTS" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>com.apple.security.cs.allow-unsigned-executable-memory</key>
  <true/>
  <key>com.apple.security.files.user-selected.read-write</key>
  <true/>
</dict>
</plist>
EOF

cp "$BIN" "$APP/Contents/MacOS/Flipgrade"
chmod +x "$APP/Contents/MacOS/Flipgrade"
mkdir -p "$APP/Contents/Resources/Fonts"
cp "$ROOT/Sources/Flipgrade/Resources/Fonts/"*.ttf "$APP/Contents/Resources/Fonts/"

echo "Signing with Developer ID…"
codesign --force --options runtime --timestamp \
  --entitlements "$ENTITLEMENTS" \
  --sign "$IDENTITY" \
  "$APP/Contents/MacOS/Flipgrade"
codesign --force --deep --options runtime --timestamp \
  --entitlements "$ENTITLEMENTS" \
  --sign "$IDENTITY" \
  "$APP"

echo "Verifying signature…"
codesign --verify --deep --strict --verbose=2 "$APP"
spctl --assess --type execute --verbose=4 "$APP" 2>&1 || true

echo "Zipping…"
# ditto preserves extended attributes / resource forks Gatekeeper cares about.
ditto -c -k --keepParent "$APP" "$ZIP"

rm -f "$ENTITLEMENTS"

echo ""
echo "Ready to share:"
echo "  $ZIP"
echo ""
echo "Note: Notarization credentials are not configured. Recipients may need"
echo "  right-click → Open  the first time (Gatekeeper)."
echo "To notarize later: xcrun notarytool store-credentials, then"
echo "  xcrun notarytool submit \"$ZIP\" --keychain-profile <name> --wait"
echo "  xcrun stapler staple \"$APP\""
file "$APP/Contents/MacOS/Flipgrade"
codesign -dv "$APP" 2>&1 | egrep 'Authority|TeamIdentifier|Identifier|Format|Signature'
